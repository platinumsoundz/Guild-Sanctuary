import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const workspace = readFileSync('src/components/AppWorkspace.tsx', 'utf8');
const guild = readFileSync('src/components/GuildWorld.tsx', 'utf8');
const css = readFileSync('src/components/GuildWorld.module.css', 'utf8');
const controller = readFileSync('src/lib/controllerInput.ts', 'utf8');

assert.match(workspace, /<GuildWorld userId=\{currentUser\?\.user\.id \?\? null\} isAuthenticated=\{isAuthenticated && !isGuest\} \/>/, 'hidden Guild shell is mounted and guest sessions are excluded');
assert.doesNotMatch(workspace, /activeNavigation === 'guild'|label:\s*'The Guild'/, 'Guild is not exposed in ordinary navigation');
assert.match(guild, /getConnectedGamepad/, 'Guild uses the shared controller abstraction');
assert.match(controller, /readGamepadDirections/, 'controller abstraction maps physical input to logical directions');
assert.match(controller, /button.value > 0.65/, 'controller abstraction supports analog button thresholds');
assert.match(controller, /horizontal < -0.45/, 'controller abstraction supports analog stick movement');
assert.match(guild, /ctrlKey && event\.shiftKey/, 'keyboard accessibility override exists');
assert.match(guild, /Orbital Drift/, 'first original browser game is present');
assert.match(guild, /localStorage\.setItem\(BEST_KEY/, 'best run is stored locally');
assert.match(guild, /No cloud rewards or cross-world sharing are enabled/, 'prototype does not claim cloud progression');
assert.match(guild, /!isAuthenticated\s*\|\|\s*!userId/, 'Guild entry requires the shared authenticated identity');
assert.match(guild, /setSeconds\(START_SECONDS\)/, 'game run has a resettable countdown');
assert.match(guild, /nextScore >= TARGET/, 'game has a defined completion condition');
assert.match(css, /prefers-reduced-motion:reduce/, 'motion respects reduced-motion preference');
assert.match(css, /env\(safe-area-inset-bottom\)/, 'entry respects mobile safe areas');
assert.ok(guild.includes("document.addEventListener('visibilitychange'"), 'background tabs pause the timer');
assert.match(guild, /querySelectorAll<HTMLElement>/, 'controller can move focus between interactive controls');
assert.ok(guild.includes('closeButtonRef.current?.focus'), 'dialog moves focus to a close control');
assert.ok(guild.includes("type GameState = 'ready' | 'playing' | 'paused' | 'won' | 'lost'"), 'trial supports an explicit paused state');
assert.ok(guild.includes("gameState === 'paused' ? 'Resume' : 'Pause'"), 'player can pause and resume from the game HUD');
assert.match(workspace, /isAuthenticated && !isGuest/, 'guest sessions cannot enter the Guild');
console.log('Guild browser Arcade contract checks passed.');
